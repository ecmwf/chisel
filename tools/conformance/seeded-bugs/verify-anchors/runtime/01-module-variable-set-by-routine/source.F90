MODULE MOD_A
  IMPLICIT NONE
#ifdef FIXTURE_DP
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(13, 300)
#else
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(6, 37)
#endif
  REAL(WP) :: XS
CONTAINS
  SUBROUTINE INIT_A(X)
    REAL(WP), INTENT(IN) :: X
    XS = 2._WP*SQRT(X)
  END SUBROUTINE INIT_A
END MODULE MOD_A
