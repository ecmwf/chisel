MODULE MOD_A
  IMPLICIT NONE
#ifdef FIXTURE_DP
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(13, 300)
#else
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(6, 37)
#endif
CONTAINS
  REAL(WP) FUNCTION RATIO4(QA)
    REAL(WP), INTENT(IN) :: QA
    RATIO4 = ((1._WP+QA)/(1._WP-QA))**4
  END FUNCTION RATIO4
END MODULE MOD_A
