MODULE MOD_A
  IMPLICIT NONE
#ifdef FIXTURE_DP
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(13, 300)
#else
  INTEGER, PARAMETER :: WP = SELECTED_REAL_KIND(6, 37)
#endif
CONTAINS
  FUNCTION PICK(R) RESULT(S)
    REAL(WP), POINTER, INTENT(IN) :: R
    REAL(WP), POINTER :: S
    REAL(WP), POINTER :: Q => NULL()
    IF (.NOT. ASSOCIATED(Q)) Q => R
    S => Q
  END FUNCTION PICK
END MODULE MOD_A
